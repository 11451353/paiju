type Props = {
  onClose: () => void
}

/** 主界面规则书：从胜负条件到具体操作，完整说明一局怎么玩。 */
export default function RulesBook({ onClose }: Props) {
  return (
    <div
      className="rules"
      role="dialog"
      aria-modal="true"
      aria-label="游戏规则书"
      onClick={onClose}
    >
      <div className="rules__panel" onClick={(e) => e.stopPropagation()}>
        <header className="rules__head">
          <div>
            <p className="rules__kicker">牌局 · 规则书</p>
            <h2 className="rules__title">从零开始的一局</h2>
          </div>
          <button type="button" className="rules__close" onClick={onClose}>
            关闭
          </button>
        </header>

        <div className="rules__body">
          <section>
            <h3>一、目标与胜负</h3>
            <ul>
              <li>
                每名玩家拥有 <strong>3 名角色</strong>，其中 1 名在前台，其余在后台。把对手的
                <strong>所有角色</strong>全部击倒，该玩家即被淘汰。
              </li>
              <li>
                2–4 人自由混战，最后一名仍有存活角色的玩家获胜。若出现所有玩家同时全灭的极端情况，
                本局判为平局。
              </li>
              <li>
                单人模式使用关卡规则：普通关卡与上面的标准胜负相同；特殊关卡在右上角
                <strong>「?」</strong>按钮里写明了独立的胜利条件（例如击杀关底角色）。
              </li>
              <li>
                角色阵亡后不会自动复活，也不会在回合开始时回满血。只有卡牌、技能或关卡机制明确写明「复活」时才会回来。
              </li>
            </ul>
          </section>

          <section>
            <h3>二、一局怎么进行</h3>
            <ul>
              <li>
                <strong>选角色：</strong>从角色池中选择 3 名不重复的角色，再指定 1 名作为初始前台。
              </li>
              <li>
                <strong>回合开始：</strong>先结算回合开始效果（复活、场地补盾等），然后每名玩家摸
                5 张牌，手牌最多补到 10 张；接着掷 1 颗六面骰，点数就是本回合的
                <strong>行动点</strong>（1–6 点）。
              </li>
              <li>
                <strong>行动阶段：</strong>从随机先手开始，按座位顺序每人行动一次。轮到你时，可以打出任意张
                付得起的牌、切换角色、弃牌换行动点，处理完后点「结束行动」把回合交给下一位玩家。
              </li>
              <li>
                <strong>结束阶段：</strong>结算持续伤害、持续回合数等状态效果；未使用的行动点清零，
                不会保留到下一回合。然后进入下一回合。
              </li>
            </ul>
          </section>

          <section>
            <h3>三、行动点与手牌</h3>
            <ul>
              <li>
                <strong>行动点（AP）</strong>是每回合的行动资源。打牌要支付牌面消耗，主动换人要消耗
                1 点；行动点不足时不能支付。
              </li>
              <li>
                每回合掷骰获得的行动点<strong>不会累积</strong>。本回合没用完的点数在结束阶段直接清零。
              </li>
              <li>
                <strong>弃牌换点：</strong>把一张手牌拖到垃圾桶，弃掉它并获得 1 点行动点，
                可以在关键时刻补足费用。
              </li>
              <li>
                每回合摸 5 张，手牌上限 10 张。牌堆不够摸时，弃牌堆会洗回牌堆继续使用。
              </li>
              <li>
                手牌里的「普攻 / 战技 / 大招」是通用技能牌，<strong>具体费用和效果由你当前的前台角色决定</strong>；
                换人后同一张牌会按新前台角色的技能结算。
              </li>
            </ul>
          </section>

          <section>
            <h3>四、前台、后台与换人</h3>
            <ul>
              <li>
                同一时间只有 1 名<strong>前台</strong>角色。单体攻击默认打向对方前台；后台角色通常不会吃到单体伤害，
                但会吃到「全体」「后台」类效果。
              </li>
              <li>
                前台阵亡后，必须从自己仍存活的后台角色中重新选择 1 名上场；如果已经没有存活角色，
                该玩家被淘汰。
              </li>
              <li>
                主动换人消耗 <strong>1 点行动点</strong>：点击自己的一名后台角色，在详情里点「换到前台」。
                部分卡牌效果会禁止当回合主动换人。
              </li>
              <li>
                角色的生命不会在回合开始时自动恢复；治疗不能超过生命上限。护盾会先于生命被消耗。
              </li>
            </ul>
          </section>

          <section>
            <h3>五、伤害、护盾与真实伤害</h3>
            <ul>
              <li>
                <strong>普通伤害</strong>的结算顺序：先计算闪避/免疫，再扣除各类减伤和护盾，
                最后才扣生命。
              </li>
              <li>
                <strong>真实伤害</strong>无视减伤和护盾，直接扣除生命；卡面上标注「真实伤害」的部分按此处理。
              </li>
              <li>
                护盾可以叠加，受到普通伤害时优先消耗；减伤可能来自场地、配饰或状态效果，
                具体数值和次数看对应卡面/状态说明。
              </li>
              <li>
                角色生命降到 0 即阵亡。部分卡牌可以让阵亡角色复活；刚复活的角色可能在本回合内免疫伤害，
                以卡面说明为准。
              </li>
            </ul>
          </section>

          <section>
            <h3>六、卡牌类型</h3>
            <ul>
              <li>
                <strong>技能牌（普攻 / 战技 / 大招）：</strong>使用当前前台角色对应的技能，支付该角色技能的费用，
                结算后进入弃牌堆。角色详情里可以查看三个技能的完整描述。
              </li>
              <li>
                <strong>场地牌：</strong>打出后装备，持续提供效果，不进入弃牌堆。每人最多装备 2 张；
                已满 2 张时再打出，需要选择一张旧场地替换。
              </li>
              <li>
                <strong>配饰牌：</strong>与场地类似，装备后持续生效，每人最多 2 张，满了需要替换。
                已装备的场地和配饰都可以点击查看详情。
              </li>
              <li>
                <strong>道具牌 / 事件牌：</strong>一次性效果，结算后进入弃牌堆。道具通常强化自己，
                事件通常改变本回合或下一回合的规则。
              </li>
              <li>
                <strong>牌堆构成：</strong>共 128 张，其中技能牌 64 张（普攻 32、战技 20、大招 12），
                场地、道具、事件、配饰各 16 张。
              </li>
            </ul>
          </section>

          <section>
            <h3>七、状态效果与召唤物</h3>
            <ul>
              <li>
                状态分为<strong>正面（增益）</strong>、<strong>负面（减益）</strong>和
                <strong>中性（资源/标记）</strong>。层数可能代表强度、剩余次数或持续回合。
              </li>
              <li>
                带持续回合/次数的状态通常在结束阶段减 1 层，归零后消失；只持续当回合的效果会在结束阶段直接移除。
                具体以状态说明为准。
              </li>
              <li>
                点击角色牌可以查看它当前身上的所有状态、技能和天赋；技能描述里的状态名也可以点开查看详细规则。
              </li>
              <li>
                部分角色会召唤召唤物。召唤物显示在手牌右侧的信息槽，点击图标可以查看剩余次数/层数和完整说明。
              </li>
            </ul>
          </section>

          <section>
            <h3>八、操作方式</h3>
            <ul>
              <li>
                <strong>打牌：</strong>把想打出的手牌拖到牌桌中央区域。需要选择目标时，会弹出目标选择窗口。
              </li>
              <li>
                <strong>弃牌：</strong>把手牌拖到垃圾桶，弃掉并获得 1 点行动点。
              </li>
              <li>
                <strong>查看详情：</strong>点击手牌、角色牌、已装备的场地/配饰、召唤物，都会打开详情面板。
                拖动过程中松手不会误触详情。
              </li>
              <li>
                <strong>换人：</strong>点击自己的后台角色，在详情里点「换到前台」（消耗 1 点行动点）。
              </li>
              <li>
                <strong>结束回合：</strong>处理完行动后点右下角「结束行动」。等待对手行动时按钮会变灰。
              </li>
              <li>
                <strong>关卡机制：</strong>对局右上角的「?」按钮可以随时查看当前关卡的阵容、行动循环和胜负条件。
              </li>
            </ul>
          </section>

          <section>
            <h3>九、单人模式</h3>
            <ul>
              <li>
                主界面点「单人模式」后先选关卡，再选 3 名角色开始挑战；关卡图标、敌方阵容和机制各不相同。
              </li>
              <li>
                <strong>测试版：</strong>标准规则，对手是 3 名空白角色，适合熟悉操作。
              </li>
              <li>
                <strong>盗罐行者：</strong>敌方有 1 名关底角色和最多 4 个容器；击杀关底角色即获胜。
                攻击时可以选择任意敌方角色作为本次目标。
              </li>
              <li>
                <strong>现代最唐：</strong>敌方由豆包和奶蛙组成，会合体成奶豆；豆包和奶蛙同时阵亡，
                或击杀奶豆即可获胜。攻击时同样可以选择敌方目标。
              </li>
            </ul>
          </section>

          <section>
            <h3>十、常见问题</h3>
            <ul>
              <li>
                <strong>牌拖不出去？</strong>先确认轮到你行动、行动点足够、当前没有等待你选择目标或复活角色。
              </li>
              <li>
                <strong>结束按钮是灰的？</strong>可能在播放结算动画，或正在等待你选择新前台、复活目标、
                鲨bee 放电目标等。
              </li>
              <li>
                <strong>技能效果和卡面不一样？</strong>技能牌按当前前台角色结算；换人后数值和效果都会变化。
              </li>
              <li>
                <strong>角色列表里找不到某些角色？</strong>部分角色只会在特定单人关卡中作为敌人出现，
                不能选为己方。
              </li>
            </ul>
            <p className="rules__note">
              新手建议：每回合先看前台角色的三个技能和费用，规划好行动点；行动点不够时果断弃牌换点；
              保护好自己的前台，同时留意对手装备和状态。
            </p>
          </section>
        </div>
      </div>
    </div>
  )
}
